-- Daily rates to the reporting currency (USD). Not a dimension, but a conformed lookup.
create table if not exists dwh.fx_rate (
    rate_date       date          not null,
    currency_key    integer       not null references dwh.dim_currency (currency_key),
    rate_to_usd     numeric(18,8) not null check (rate_to_usd > 0),
    primary key (currency_key, rate_date)
);

