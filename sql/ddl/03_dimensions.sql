-- --------------------------------------------------------------- dim_merchant
-- Slowly changing dimension, type 2: one row per version of a merchant.
-- valid_from is inclusive and valid_to exclusive; the open version ends 9999-12-31.
-- Type 2 attributes: category, mcc, country, risk tier, pricing plan, status.
-- Type 1 attribute: merchant_name (a rename is treated as a correction).
create table if not exists dwh.dim_merchant (
    merchant_key    integer generated by default as identity primary key,
    merchant_id     varchar(20)  not null,               -- business key
    merchant_name   varchar(120) not null,
    category        varchar(40)  not null,
    mcc             char(4)      not null,
    country_code    char(2)      not null,
    risk_tier       varchar(10)  not null,
    pricing_plan    varchar(20)  not null,
    status          varchar(12)  not null,
    onboarding_date date,
    valid_from      date         not null,
    valid_to        date         not null,
    is_current      boolean      not null,
    row_hash        char(32)     not null,
    check (valid_from < valid_to)
);

create unique index if not exists dim_merchant_one_current on dwh.dim_merchant (merchant_id) where is_current;
create unique index if not exists dim_merchant_version on dwh.dim_merchant (merchant_id, valid_from);

insert into dwh.dim_merchant (merchant_key, merchant_id, merchant_name, category, mcc, country_code, risk_tier,
                              pricing_plan, status, onboarding_date, valid_from, valid_to, is_current, row_hash)
values (-1, 'UNKNOWN', 'Unknown merchant', 'Unknown', '0000', 'ZZ', 'Unknown', 'Unknown', 'Unknown', null,
        date '1900-01-01', date '9999-12-31', true, repeat('0', 32))
on conflict do nothing;
