-- Dimensions. Integer surrogate keys throughout; key -1 is the Unknown member of each
-- dimension, so a fact never has a null or dangling foreign key.

-- ------------------------------------------------------------------ dim_date
create table if not exists dwh.dim_date (
    date_key        integer      primary key,            -- yyyymmdd
    full_date       date         not null unique,
    day_of_month    smallint     not null,
    day_of_week     smallint     not null,               -- 1 = Monday ... 7 = Sunday
    day_name        varchar(9)   not null,
    week_of_year    smallint     not null,               -- ISO week
    month_number    smallint     not null,
    month_name      varchar(9)   not null,
    year_month      char(7)      not null,               -- yyyy-mm
    quarter_number  smallint     not null,
    quarter_label   char(2)      not null,               -- Q1 .. Q4
    year            smallint     not null,
    fiscal_year     smallint     not null,               -- fiscal year starts 1 July
    fiscal_quarter  smallint     not null,
    fiscal_period   smallint     not null,               -- 1 = July ... 12 = June
    is_weekend      boolean      not null,
    is_holiday      boolean      not null
);

-- Fills the calendar for a range of dates. Safe to call again with an overlapping range.
create or replace function dwh.populate_dim_date(first_date date, last_date date) returns integer
language sql as $$
    with inserted as (
        insert into dwh.dim_date
        select
            to_char(d, 'YYYYMMDD')::integer,
            d::date,
            extract(day from d)::smallint,
            extract(isodow from d)::smallint,
            trim(to_char(d, 'Day')),
            extract(week from d)::smallint,
            extract(month from d)::smallint,
            trim(to_char(d, 'Month')),
            to_char(d, 'YYYY-MM'),
            extract(quarter from d)::smallint,
            'Q' || extract(quarter from d)::text,
            extract(year from d)::smallint,
            (extract(year from d) + case when extract(month from d) >= 7 then 1 else 0 end)::smallint,
            (((extract(month from d)::integer + 5) % 12) / 3 + 1)::smallint,
            ((extract(month from d)::integer + 5) % 12 + 1)::smallint,
            extract(isodow from d) >= 6,
            to_char(d, 'MM-DD') in ('01-01', '12-25', '12-26')
        from generate_series(first_date, last_date, interval '1 day') as d
        on conflict (date_key) do nothing
        returning 1
    )
    select count(*)::integer from inserted;
$$;

